"""Plain-language directions for the six manual tasks; no answer hints."""
from src.workbench.manual_study import baseline


def step_guidance(step, task):
    busy = bool(task and task["status"] in {"pending", "modeling", "revising", "solving", "executing"})
    purpose, actions, question, placeholder, page, action = {
        "T1": ("告诉系统工厂的情况，开始一份生产计划。",
               ["打开“新建优化任务”，阅读工厂的业务需求。", "点击“生成可确认的模型”，等待系统整理生产规则。"],
               "创建任务时的操作感受（可选）", "例如：是否容易找到开始入口；有什么看不懂的地方。", "新建优化任务", "去创建生产任务"),
        "T2": ("看看系统有没有理解你想做的事。这里的“模型”，就是系统整理出的生产目标和规则。",
               ["阅读“系统对业务目标的理解”“需要决定什么”和业务规则。", "再对照业务原文，用自己的话说出系统想解决的问题和生产要求。"],
               "系统想帮工厂解决什么问题？生产时要遵守哪些要求？", "请写你自己的理解，不需要使用公式或专业术语。", "模型查看与确认", "去阅读生产目标和规则"),
        "T3": ("检查系统整理的规则是否有遗漏或理解错误。这里不要求你证明数学公式。",
               ["把业务原文与系统列出的规则、数量限制和假设对照。", "记录你发现的遗漏、误解或不合理之处；没有发现也可如实说明。"],
               "有没有遗漏、理解错误或不合理的地方？", "可以写发现了什么，也可以写“没有发现”或仍不确定的地方。", "模型查看与确认", "去核对生产规则"),
        "T4": ("让系统知道新的生产限制，并保留修改前后的两份计划。",
               ["在“补充需求”输入框告诉系统：A 产品每天最多只能生产 100 件。", "点击“补充需求并重新建模”，等待后查看新规则是否加入。"],
               "补充新要求时的操作感受（可选）", "例如：是否找到输入位置；提交后是否知道系统更新了什么。", "模型查看与确认", "去补充新的生产要求"),
        "T5": ("让系统算出建议产量，再判断这份建议能不能用于实际生产。“求解”就是计算方案。",
               ["先检查新要求是否已加入，勾选确认并点击“确认模型并求解”。", "计算完成后点击“查看求解结果”，阅读建议数量、利润和验证说明。"],
               "A、B 分别生产多少件？预计利润是多少？还有什么需要确认？", "请根据你看到的结果回答，也可说明仍有疑问的地方。", "模型查看与确认", "去确认并计算新方案"),
        "T6": ("比较修改前后的两份方案，想一想怎样向老板解释。两份结果也可能相同。",
               ["查看“前后方案对比”中的基准版本 v1 和当前版本。", "对照数量、利润和新增要求，用自己的话解释差异或没有差异的原因。"],
               "两份计划有什么不同？你会怎样向老板解释？", "请写你的解释，不要求使用专业术语。", "前后方案对比", "去比较两份生产计划"),
    }[step]
    if step == "T1" and task:
        page, action = "模型查看与确认", "查看系统整理的生产规则"
        actions = ["生产任务已创建，不需要重复新建。", "在本页下方“本步记录”写下操作感受和遇到的问题，提交后进入阅读规则的步骤。"]
    if step == "T4" and task and not baseline(task):
        actions = ["先阅读初始规则，勾选确认并点击“确认模型并求解”。", "计算完成后查看并保留第一份方案，再返回这里补充 A 最多 100 件的新要求。"]
        action = "先确认并计算初始方案"
    if step == "T5" and task and task.get("solver"):
        page, action = "求解结果与验证", "去查看建议数量和利润"
        actions = ["当前方案已经计算。阅读“本次生产决策建议”和数量图，看看两种产品分别安排多少。", "核对预计利润、验证说明和仍需确认的事项，在下方记录你的理解。"]
    if busy:
        page, action = "Agent 工作流", "查看处理进度"
        actions = ["系统正在处理，请查看当前进度；处理完成后页面会提供继续入口。", "等待过程中如有不清楚的地方，也可以在下方先保存问题，不必提前结束本步。"]
    return {"purpose": purpose, "actions": actions, "question": question, "placeholder": placeholder,
            "page": page, "action": action}
